function toUnits(amount, decimals) {
	const [whole, frac = ""] = amount.trim().split(".");
	const f = (frac + "0".repeat(decimals)).slice(0, decimals);
	return BigInt(whole || "0") * 10n ** BigInt(decimals) + BigInt(f || "0");
}
