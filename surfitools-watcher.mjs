/**
* SurfiTools payment watcher — runs on GitHub Actions (repo surfitools/surfibox-watcher) every 5 minutes,
* checking every 30 seconds, so crypto payments are approved even when no admin page is open.
* It runs the exact same check as the admin tab (src/lib/verify.ts → verifyOnce), and only when
* "Approve payments automatically" is on in Admin → Payments.
*
* Env: SURFITOOLS_SERVICE_ACCOUNT (service-account JSON), SURFITOOLS_DATABASE_URL,
*      RUN_SECONDS (default 270), EVERY_SECONDS (default 30), TRONGRID_API_KEY (optional)
* Build: npm run watcher:build
*/
const account = JSON.parse(process.env.SURFITOOLS_SERVICE_ACCOUNT || "{}");
const url = process.env.SURFITOOLS_DATABASE_URL;
if (!account.private_key || !url) {
	console.log("SurfiTools watcher: SURFITOOLS_SERVICE_ACCOUNT not set — skipped.");
	process.exit(0);
}
if (process.env.TRONGRID_API_KEY) setTronGridKey(process.env.TRONGRID_API_KEY);
const app = initializeApp({
	credential: cert(account),
	databaseURL: url
}, "surfitools");
const database = getDatabase(app);
useAdminDatabase(database);
const read = async (path) => (await database.ref(path).get()).val();
const log = (...a) => console.log((/* @__PURE__ */ new Date()).toISOString().slice(11, 19), ...a);
/** Same as cryptoEnabled() on the checkout page. */
function cryptoEnabled(cfg) {
	return ASSETS.some((a) => {
		const w = cfg[a.coin];
		return w?.enabled && w.address.trim() && (a.symbol === "USDT" ? w.acceptUsdt : true);
	});
}
async function tick() {
	const cfg = normalizePayments(await read("payConfig"));
	if (!cfg.autoApprove || !cryptoEnabled(cfg)) return log("automatic approval is off in Admin → Payments");
	const raw = await read("payments") ?? {};
	const payments = Object.entries(raw).flatMap(([uid, list]) => Object.entries(list ?? {}).map(([id, p]) => normalizePayment({
		...p,
		id,
		uid
	})));
	const plans = Object.entries(await read("plans") ?? {}).map(([id, p]) => normalizePlan({
		...p,
		id
	}));
	const tools = Object.entries(await read("tools") ?? {}).map(([id, t]) => normalizeTool({
		...t,
		id
	}));
	const open = payments.filter((p) => p.status === "awaiting" || p.status === "pending").length;
	const approved = await verifyOnce(payments, plans, tools, cfg);
	log(`checked ${open} open payment(s), ${approved} approved`);
}
const runFor = Number(process.env.RUN_SECONDS || 270) * 1e3;
const every = Number(process.env.EVERY_SECONDS || 30) * 1e3;
const started = Date.now();
for (;;) {
	try {
		await tick();
	} catch (e) {
		log("check failed:", e instanceof Error ? e.message : e);
	}
	if (Date.now() - started + every > runFor) break;
	await new Promise((r) => setTimeout(r, every));
}
await deleteApp(app);
if (process.platform !== "win32") process.exit(0);
